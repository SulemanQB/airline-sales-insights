"""One-page commercial summary as HTML (self-contained) and PDF."""
from __future__ import annotations

import base64
import html
import textwrap
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.image as mpimg  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from . import config as C


def headline(res: dict) -> list[tuple[str, str]]:
    fy = res["fy"].set_index("fin_year")
    a, b = fy.iloc[-2], fy.iloc[-1]
    mix, tv, fc = res["mix"], res["target"], res["forecast"]
    return [
        (f"{fy.index[-1]} gross revenue", f"${b.gross / 1e6:,.1f}m ({b.gross / a.gross - 1:+.1%} YoY)"),
        (f"{fy.index[-1]} net after distribution", f"${b.net_after_dist / 1e6:,.1f}m ({b.net_after_dist / a.net_after_dist - 1:+.1%} YoY)"),
        ("Target attainment, last 6 months", f"{tv['network_attainment_recent']:.1%} (ex-{tv['worst_route']}: {tv['network_attainment_ex_worst']:.1%})"),
        ("NDC share of agency bookings", f"{mix['ndc_share_first6']:.0%} → {mix['ndc_share_last6']:.0%}"),
        ("Cost of sale", f"{mix['cos_first6']:.2%} → {mix['cos_last6']:.2%} of gross revenue"),
        ("Next-quarter revenue forecast", f"${fc['forecast_total'] / 1e6:,.1f}m (backtest MAPE {fc['models'][fc['best_model']]:.1f}%)"),
    ]


def _b64(p: Path) -> str:
    return base64.b64encode(Path(p).read_bytes()).decode()


def build_html(res: dict, charts: dict, out: Path) -> Path:
    kpis = "".join(f"<div class='kpi'><div class='l'>{html.escape(k)}</div><div class='v'>{html.escape(v)}</div></div>"
                   for k, v in headline(res))
    recs = "".join(f"<li><b>{html.escape(r['title'])}</b>: {html.escape(r['impact_text'])}. "
                   f"<span class='ev'>{html.escape(r['evidence'])}</span></li>" for r in res["recs"])
    imgs = "".join(f"<img src='data:image/png;base64,{_b64(charts[k])}'/>"
                   for k in ["revenue_vs_target", "channel_mix", "route_attainment", "forecast"])
    last = pd.Timestamp(res["kpi"].month_start.max())
    doc = f"""<!doctype html><html><head><meta charset='utf-8'><title>{C.AIRLINE} commercial one-pager</title>
<style>body{{font-family:Segoe UI,Arial,sans-serif;max-width:1050px;margin:20px auto;color:#1d2733}}
h1{{color:#14365d;margin:0}} .sub{{color:#8a8f98;margin-bottom:12px}}
.kpis{{display:grid;grid-template-columns:repeat(3,1fr);gap:8px}} .kpi{{background:#eef4f8;border-left:4px solid #1b9aaa;padding:8px}}
.l{{font-size:12px;color:#55606e}} .v{{font-size:17px;font-weight:600;color:#14365d}}
.charts{{display:grid;grid-template-columns:1fr 1fr;gap:6px;margin-top:10px}} img{{width:100%}}
li{{margin-bottom:6px}} .ev{{color:#55606e;font-size:13px}}</style></head><body>
<h1>{C.AIRLINE}: Sales &amp; Distribution one-pager</h1>
<div class='sub'>Data to {last:%B %Y} · synthetic data · regenerated by <code>make report</code></div>
<div class='kpis'>{kpis}</div><div class='charts'>{imgs}</div>
<h2>Recommendations</h2><ol>{recs}</ol></body></html>"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8")
    return out


def _esc(t: str) -> str:
    """Stop matplotlib reading dollar signs as maths markup."""
    return t.replace("$", r"\$")


def build_pdf(res: dict, charts: dict, out: Path) -> Path:
    fig = plt.figure(figsize=(8.27, 11.69))  # A4 portrait
    last = pd.Timestamp(res["kpi"].month_start.max())
    fig.text(0.05, 0.965, f"{C.AIRLINE}: Sales & Distribution one-pager", fontsize=15, weight="bold", color="#14365d")
    fig.text(0.05, 0.948, f"Data to {last:%B %Y} · synthetic data · regenerated by `make report`", fontsize=8, color="#8a8f98")
    for i, (k, v) in enumerate(headline(res)):
        x, y = 0.05 + (i % 3) * 0.31, 0.915 - (i // 3) * 0.045
        fig.text(x, y, k, fontsize=7, color="#55606e")
        fig.text(x, y - 0.018, _esc(v), fontsize=9, weight="bold", color="#14365d")
    for i, key in enumerate(["revenue_vs_target", "channel_mix", "route_attainment", "forecast"]):
        ax = fig.add_axes([0.03 + (i % 2) * 0.48, 0.60 - (i // 2) * 0.20, 0.46, 0.20])
        ax.imshow(mpimg.imread(charts[key])); ax.axis("off")
    fig.text(0.05, 0.37, "Recommendations", fontsize=12, weight="bold", color="#14365d")
    y = 0.35
    for i, r in enumerate(res["recs"], start=1):
        body = textwrap.fill(f"{i}. {r['title']}: {r['impact_text']}.", 110)
        fig.text(0.05, y, _esc(body), fontsize=8, weight="bold", va="top")
        y -= 0.016 * (body.count("\n") + 1)
        ev = textwrap.fill(r["evidence"], 120)
        fig.text(0.07, y, _esc(ev), fontsize=7, color="#55606e", va="top")
        y -= 0.014 * (ev.count("\n") + 1) + 0.010
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out)
    plt.close(fig)
    return out
